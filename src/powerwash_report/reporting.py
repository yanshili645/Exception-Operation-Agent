from __future__ import annotations

import csv
import html
import json
from pathlib import Path


FIELDS = [
    "report_date", "code", "severity", "category", "job_number", "customer", "truck",
    "employee", "planned", "actual", "variance", "evidence", "owner",
    "recommended_action", "source", "status", "resolution",
]


def write_outputs(output_dir: Path, summary: dict, narrative: dict, exceptions: list[dict], source_meta: dict):
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "exceptions.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(exceptions)
    (output_dir / "exceptions.json").write_text(json.dumps(exceptions, indent=2, ensure_ascii=False), encoding="utf-8")

    payload = {**summary, "ai_narrative": narrative}
    (output_dir / "management_summary.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    (output_dir / "source_snapshot.json").write_text(json.dumps(source_meta, indent=2), encoding="utf-8")
    (output_dir / "daily_exception_report.html").write_text(_html_report(summary, narrative, exceptions), encoding="utf-8")


def _html_report(summary: dict, narrative: dict, exceptions: list[dict]) -> str:
    def esc(value):
        return html.escape(str(value or ""))

    counts = summary["exception_counts"]
    cards = [
        ("Overall status", summary["overall_status"]),
        ("Jobs completed", f"{summary['jobs_completed']} / {summary['jobs_scheduled']}"),
        ("Critical exceptions", counts["Critical"]),
        ("High exceptions", counts["High"]),
        ("Labour variance", f"{summary['labour_variance_hours']:+.2f} h"),
    ]
    card_html = "".join(f'<div class="card"><span>{esc(k)}</span><strong>{esc(v)}</strong></div>' for k, v in cards)
    rows = "".join(
        "<tr>" + "".join(f"<td>{esc(row.get(col))}</td>" for col in
        ("severity", "code", "job_number", "customer", "employee", "actual", "variance", "owner", "recommended_action")) + "</tr>"
        for row in exceptions
    )
    attention = "".join(f"<li>{esc(x)}</li>" for x in narrative.get("management_attention", [])) or "<li>No urgent exceptions.</li>"
    actions = "".join(f"<li>{esc(x)}</li>" for x in narrative.get("recommended_actions", [])) or "<li>No immediate action required.</li>"
    return f"""<!doctype html>
<html><head><meta charset="utf-8"><title>PowerWash Daily Exception Report</title>
<style>
body{{font-family:Arial,sans-serif;color:#1f2937;margin:32px;background:#f7f9fc}} .wrap{{max-width:1400px;margin:auto;background:white;padding:28px;border-radius:10px}}
h1{{margin:0;color:#17365d}} .sub{{color:#64748b;margin:6px 0 22px}} .cards{{display:grid;grid-template-columns:repeat(5,1fr);gap:12px}}
.card{{border-top:4px solid #2f75b5;background:#f2f6fb;padding:14px}} .card span{{display:block;font-size:12px;color:#64748b}} .card strong{{font-size:22px}}
.panel{{margin-top:22px;padding:16px;background:#fff8e1;border-left:4px solid #f4b183}} h2{{font-size:18px;color:#17365d}}
table{{width:100%;border-collapse:collapse;font-size:12px;margin-top:12px}} th{{background:#17365d;color:white;text-align:left;padding:8px}} td{{border-bottom:1px solid #dbe3ee;padding:8px;vertical-align:top}}
tr:has(td:first-child:nth-last-child(n)){{background:white}} .foot{{margin-top:18px;color:#64748b;font-size:11px}}
@media(max-width:900px){{.cards{{grid-template-columns:1fr 1fr}}}}
</style></head><body><div class="wrap">
<h1>PowerWash Daily Operations Exception Report</h1><div class="sub">Reporting date {esc(summary['report_date'])} · Read-only MVP</div>
<div class="cards">{card_html}</div>
<div class="panel"><h2>Suggested interpretation</h2><p>{esc(narrative.get('suggested_interpretation'))}</p>
<h3>Management attention</h3><ol>{attention}</ol><h3>Recommended actions</h3><ol>{actions}</ol>
<small>{esc(narrative.get('source'))} · Confidence: {esc(narrative.get('confidence'))}</small></div>
<h2>Exception register</h2><table><thead><tr><th>Severity</th><th>Code</th><th>Job</th><th>Customer</th><th>Employee</th><th>Actual</th><th>Variance</th><th>Owner</th><th>Recommended action</th></tr></thead><tbody>{rows}</tbody></table>
<div class="foot">All exception codes and severities were generated by deterministic rules. AI content is advisory and cannot modify source evidence.</div>
</div></body></html>"""
